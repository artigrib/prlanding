// Generates backend/bridge-client/schemas.js from src/schemas.ts (single source of truth).
// The tab re-validates every relayed call against these schemas. `session` is removed: the tab never sees it.
// Usage: node scripts/export-schemas.ts [--check]

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';
import { GRIPPER_LIMITS_PCT, Inputs, JOINT_LIMITS_DEG, MOTION_TOOLS, TAB_TOOLS, VIEWS } from '../src/schemas.ts';

export function buildSchemas(): Record<string, unknown> {
  const tools: Record<string, unknown> = {};
  for (const t of TAB_TOOLS) {
    const js = z.toJSONSchema(Inputs[t], { target: 'draft-2020-12' }) as any;
    delete js.$schema;
    delete js.properties.session;
    js.required = (js.required || []).filter((r: string) => r !== 'session');
    if (!js.required.length) delete js.required;
    tools[t] = js;
  }
  return {
    $comment: 'GENERATED by backend/bridge/scripts/export-schemas.ts from backend/bridge/src/schemas.ts. Do not edit.',
    protocol: 1,
    limits: { joints_deg: JOINT_LIMITS_DEG, gripper_pct: GRIPPER_LIMITS_PCT },
    views: VIEWS,
    motion_tools: [...MOTION_TOOLS],
    tools
  };
}

const out = fileURLToPath(new URL('../../bridge-client/schemas.js', import.meta.url));
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = '// GENERATED by backend/bridge/scripts/export-schemas.ts from backend/bridge/src/schemas.ts. Do not edit.\nexport default ' + JSON.stringify(buildSchemas(), null, 1) + ';\n';
  if (process.argv.includes('--check')) {
    if (readFileSync(out, 'utf8') !== text) { console.error('schemas.js is stale: run npm run schemas'); process.exit(1); }
    console.log('schemas.js up to date');
  } else {
    writeFileSync(out, text);
    console.log('wrote', out);
  }
}
