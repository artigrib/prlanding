"""Regenerate sim/so101/objects/manifest.json and LICENSES.md from the per-object <id>/<id>.json records.

Re-applies the licence allow list (an object whose licence is no longer allowed is left out and reported),
checks files exist and the GLB budget holds. Output is deterministic (sorted, no timestamps).

Usage: python -I tools/assets/manifest.py [--objects sim/so101/objects] [--check]
  --check  exit 1 if manifest.json / LICENSES.md would change (CI guard)
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import OBJECTS_DIR, detail, license_decision, load_policy, status  # noqa: E402

FIELDS = ("id", "name_cs", "name_en", "category", "mass_kg", "size_m", "friction", "graspable", "body",
          "license", "license_url", "attribution", "source_url", "files")


def build(objects_dir, policy):
    od = Path(objects_dir)
    entries, problems = [], []
    for d in sorted(p for p in od.iterdir() if p.is_dir() and not p.name.startswith(".")):
        rec_path = d / f"{d.name}.json"
        if not rec_path.is_file():
            continue
        rec = json.loads(rec_path.read_text(encoding="utf-8"))
        spdx, _, why = license_decision([("record", rec.get("license"))], policy)
        if not spdx:
            problems.append(f"{d.name}: {why}")
            continue
        if not rec.get("attribution") or not rec.get("source_url"):
            problems.append(f"{d.name}: attribution/source missing")
            continue
        sizes = {}
        for k, rel in rec["files"].items():
            f = od / rel
            if not f.is_file():
                problems.append(f"{d.name}: missing {rel}")
                break
            sizes[k] = f.stat().st_size
        else:
            if sizes["glb"] > policy["budget"]["glb_max_bytes"]:
                problems.append(f"{d.name}: GLB over budget")
                continue
            e = {k: rec.get(k) for k in FIELDS}
            e["bytes"] = sizes
            if rec.get("name_cs_auto"):
                e["name_cs_auto"] = True
            entries.append(e)
    manifest = {"version": 1, "units": {"mass": "kg", "size": "m (x y z, Z-up, body origin = bottom centre)"},
                "objects": entries}
    return manifest, problems


def licenses_md(manifest):
    lines = ["# Objects: licences and attribution", "",
             "Generated by `tools/assets/manifest.py` from the per-object records. Every object below may be used",
             "commercially and redistributed in modified form under the licence named; the attribution line is the",
             "credit required by that licence. The converted files (decimated GLB, convex collision hulls, MJCF)",
             "are modifications made by printedrobotics.cz.", "",
             "| Object | Licence | Attribution | Source |", "|---|---|---|---|"]
    for e in manifest["objects"]:
        lic = f"[{e['license']}]({e['license_url']})" if e.get("license_url") else e["license"]
        lines.append(f"| {e['name_cs']} (`{e['id']}`) | {lic} | {e['attribution']} | <{e['source_url']}> |")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--objects", default=str(OBJECTS_DIR))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    od = Path(a.objects)
    manifest, problems = build(od, load_policy())
    mtext = json.dumps(manifest, indent=1, ensure_ascii=False) + "\n"
    ltext = licenses_md(manifest)
    if a.check:
        same = ((od / "manifest.json").is_file() and (od / "manifest.json").read_text(encoding="utf-8") == mtext
                and (od / "LICENSES.md").is_file() and (od / "LICENSES.md").read_text(encoding="utf-8") == ltext)
        status(f"manifest: {'up to date' if same else 'OUT OF DATE'}; {len(problems)} problem(s)")
        return 0 if same and not problems else 1
    (od / "manifest.json").write_text(mtext, encoding="utf-8")
    (od / "LICENSES.md").write_text(ltext, encoding="utf-8")
    for p in problems:
        detail(p)
    status(f"manifest: {len(manifest['objects'])} object(s), {len(problems)} left out")
    return 0


if __name__ == "__main__":
    sys.exit(main())
