// Builds the site's single copy of three.js into vendor/three/ (used by the product-page 3D viewer, the SO-101
// sim and the arena through an importmap: "three" -> vendor/three/three.module.min.js,
// "three/addons/" -> vendor/three/addons/). Source: the three version pinned in sim/arena/package-lock.json.
//
//   cd sim/arena && npm ci && npm run vendor-three      # rewrite vendor/three/
//   CI (arena job) re-runs it and fails if the committed files differ.
//
// three.module.js + three.core.js are bundled into one minified ES module; each addon in ADDONS (and the addon
// files they import) is minified on its own, keeping its `from 'three'` and relative imports.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const req = createRequire(path.join(ROOT, 'sim/arena/package.json'));
const esbuild = req('esbuild');
const THREE = path.join(ROOT, 'sim/arena/node_modules/three');
const VERSION = JSON.parse(fs.readFileSync(path.join(THREE, 'package.json'), 'utf8')).version;
const OUT = path.join(ROOT, 'vendor/three');

// every addon a page imports (three/addons/<path>); their own relative imports are added automatically
const ADDONS = [
  'controls/OrbitControls.js',
  'environments/RoomEnvironment.js',
  'geometries/ConvexGeometry.js',
  'libs/meshopt_decoder.module.js',
  'loaders/GLTFLoader.js',
  'utils/BufferGeometryUtils.js',
];
const BANNER = (f) => `/* three.js r${VERSION.split('.')[1]} (npm three@${VERSION}) ${f}, minified by tools/vendor-three.mjs. Copyright 2010-2026 Three.js Authors, MIT (LICENSE). */`;

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, 'addons'), { recursive: true });

await esbuild.build({
  entryPoints: [path.join(THREE, 'build/three.module.js')], bundle: true, format: 'esm', minify: true,
  target: 'es2020', legalComments: 'none', banner: { js: BANNER('build/three.module.js + three.core.js') },
  outfile: path.join(OUT, 'three.module.min.js'), logLevel: 'warning',
});

const todo = [...ADDONS], done = new Set();
while (todo.length) {
  const rel = todo.shift();
  if (done.has(rel)) continue; done.add(rel);
  const src = fs.readFileSync(path.join(THREE, 'examples/jsm', rel), 'utf8');
  for (const m of src.matchAll(/^\s*(?:import|export)\b[^;]*?from\s*['"](\.{1,2}\/[^'"]+)['"]/gm)) {
    todo.push(path.posix.normalize(path.posix.join(path.posix.dirname(rel), m[1])));
  }
  const { code } = await esbuild.transform(src, { loader: 'js', format: 'esm', minify: true, target: 'es2020', legalComments: 'none', banner: BANNER('examples/jsm/' + rel) });
  fs.mkdirSync(path.dirname(path.join(OUT, 'addons', rel)), { recursive: true });
  fs.writeFileSync(path.join(OUT, 'addons', rel), code);
}
fs.copyFileSync(path.join(THREE, 'LICENSE'), path.join(OUT, 'LICENSE'));
fs.writeFileSync(path.join(OUT, 'NOTICE.txt'), `three.js ${VERSION} (https://threejs.org, npm package three@${VERSION}), MIT licence (LICENSE).
Generated by tools/vendor-three.mjs: build/three.module.js and build/three.core.js bundled into three.module.min.js;
addons from examples/jsm/ minified one file each under addons/ (${[...done].sort().join(', ')}).
Code is otherwise unchanged. The meshoptimizer decoder (addons/libs/meshopt_decoder.module.js) is
Copyright (C) 2016-2026 Arseny Kapoulkine, MIT, as shipped in three@${VERSION}.
Do not edit; re-run: cd sim/arena && npm ci && npm run vendor-three
`);
let total = 0;
for (const f of [...walk(OUT)].sort()) { const s = fs.statSync(f).size; total += s; console.log(String(s).padStart(8), path.relative(ROOT, f)); }
console.log(String(total).padStart(8), 'total');
function* walk(d) { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) yield* walk(p); else yield p; } }
