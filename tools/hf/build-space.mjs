// Assembles two static Hugging Face Spaces from the committed sims:
//   dist-hf/so101-sim  ← sim/so101 (MuJoCo WASM arm simulator, setup wizard, object library, LeRobot export)
//   dist-hf/arena      ← sim/arena (antweight combat arena, prebuilt build/)
// Run from the repo root:  node tools/hf/build-space.mjs   (no dependencies; Node ≥ 18)
// Published by .github/workflows/hf-publish.yml; owner steps in docs/hf.md.
//
// Each Space keeps the site's folder layout (sim/<name>/…, assets/i18n.js, models/…), so every relative
// path inside the sims works unchanged; nothing in sim/ is edited. Added per Space:
//   index.html   entry point: forwards to the sim with ?lang=en (English default; CZ switch in the sim header
//                keeps working; a visitor's saved choice wins)
//   hf-space.js  tiny shim loaded by every page: links back to the website (../../sada/…, ../../) point at
//                https://printedrobotics.cz (English pages when the sim runs in English) and open in a new
//                tab (a Space runs in an iframe); adds one small, dismissible "real kit" link. No tracking.
//   README.md    Space card (YAML front-matter: sdk static, tags, licence) with attributions
//   LICENSE.md   licences of everything in the Space
import fs from 'node:fs';
import path from 'node:path';
import { walkGraph } from './imports.mjs';

const ROOT = process.cwd();
const OUT = path.join(ROOT, 'dist-hf');
const SITE = 'https://printedrobotics.cz';
// The repo has no declared licence for printedrobotics.cz's own code. Set HF_CODE_LICENSE (an HF licence id
