const CODE_LICENSE = (process.env.HF_CODE_LICENSE || '').trim().toLowerCase();
const MB = 1024 * 1024;
const LIMITS = { file: 50 * MB, space: 200 * MB, lfsHint: 10 * MB };

if (!fs.existsSync(path.join(ROOT, 'sim/so101/index.html'))) { console.error('run from the repo root'); process.exit(1); }

const rel = (p) => path.relative(ROOT, p).split(path.sep).join('/');
function copy(src, dst, skip = () => false) {
  const st = fs.statSync(src);
  if (st.isDirectory()) {
    for (const e of fs.readdirSync(src).sort()) {
      const s = path.join(src, e);
      if (skip(rel(s), e)) continue;
      copy(s, path.join(dst, e), skip);
    }
  } else {
    fs.mkdirSync(path.dirname(dst), { recursive: true });
    fs.copyFileSync(src, dst);
  }
}
function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir)) { const p = path.join(dir, e); fs.statSync(p).isDirectory() ? walk(p, out) : out.push(p); }
  return out;
}
const write = (p, s) => { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, s); };

// dev-only material never goes to a Space
const DEV = /(^|\/)(tests?|tools|node_modules|src\/\.\.\.)(\/|$)|\.(md|cjs)$|(^|\/)package(-lock)?\.json$|(^|\/)\./;
const keepMd = new Set(['sim/so101/objects/LICENSES.md']);
const skipDev = (r, name) => (DEV.test(r) && !keepMd.has(r)) || name.startsWith('.');

// Files a Space imports from outside the folders copied above (e.g. the AI panel's
// ../../../../backend/bridge-client/agent-bridge.js and its imports) are copied in from the repo at the same
// relative path, following the static import graph. Dev-only files are never pulled in; anything still
// unresolved fails the build (tools/hf/check-imports.mjs runs the same walk in CI).
function pullImports(D) {
  const pulled = [];
  const problems = walkGraph(D, { onMissing: (t) => {
    const r = path.relative(D, t).split(path.sep).join('/'), src = path.join(ROOT, r);
    if (r.startsWith('..') || skipDev(r, path.basename(r)) || !fs.existsSync(src) || !fs.statSync(src).isFile()) return false;
    copy(src, t); pulled.push(r); return true;
  } });
  if (pulled.length) console.log(`${rel(D)}: pulled in ${pulled.sort().join(', ')}`);
  if (problems.length) throw new Error(`${rel(D)}: unresolved imports:\n  ` + problems.map((p) => `${path.relative(D, p.from)} -> ${p.spec} (${p.problem})`).join('\n  '));
}

/* ---------- shared pieces ---------- */
function shim({ kitText, side = 'left' }) {
  // kept small and dependency-free; runs before the sim modules
  return `// Hugging Face Space shim (generated by tools/hf/build-space.mjs). No tracking, no network requests.
(function () {
  'use strict';
  var SITE = ${JSON.stringify(SITE)}, KIT = ${JSON.stringify(kitText)};
  function en() { return document.documentElement.getAttribute('lang') === 'en'; }
  function map(a) {
    var h = a.getAttribute('href');
    if (!h || /^(#|mailto:|javascript:|data:|blob:)/.test(h) || a.hasAttribute('download')) return;
    var u; try { u = new URL(h, location.href); } catch (e) { return; }
    if (u.origin === location.origin) {
      // the sims, their notices and the Space files stay here; everything else is the website
      if (/^\\/(sim\\/|models\\/|assets\\/|LICENSE\\.md$|README\\.md$)/.test(u.pathname)) return;
      var p = u.pathname, q = u.search + u.hash;
      if (en()) {
        var m = /^\\/sada\\/([^/]+)\\/?$/.exec(p);
        if (m) p = '/en/kit/' + m[1] + '/';
        else if (p === '/' || p === '/index.html') p = '/en/';
        else if (p === '/kviz.html') p = '/en/quiz/';
      }
      var nh = SITE + p + q;
      if (nh !== h) a.setAttribute('href', nh);
      u = new URL(nh);
    }
    if (u.origin !== location.origin && a.target !== '_blank') { a.target = '_blank'; a.rel = 'noopener'; }
  }
  function fix(root) { if (root && root.querySelectorAll) { if (root.matches && root.matches('a[href]')) map(root); root.querySelectorAll('a[href]').forEach(map); } }
  function badge() {
    if (document.getElementById('hf-kit')) return;
    try { if (sessionStorage.getItem('hf-kit-x')) return; } catch (e) {}
    var t = KIT[en() ? 'en' : 'cs'], d = document.createElement('div');
    d.id = 'hf-kit'; d.lang = en() ? 'en' : 'cs';
    d.innerHTML = '<a href="' + SITE + t.path + '" target="_blank" rel="noopener">' + t.text + ' <span aria-hidden="true">\\u2197</span></a><button type="button" aria-label="' + t.close + '">\\u00d7</button>';
    var s = document.createElement('style');
    s.textContent = '#hf-kit{position:fixed;${side}:8px;bottom:8px;z-index:4;display:flex;align-items:center;max-width:calc(100vw - 16px);background:#fff;border:1px solid #0E0E0E;font:500 12px/1.2 "Geist Mono",ui-monospace,monospace;box-shadow:0 2px 8px rgba(0,0,0,.08)}' +
      '#hf-kit a{color:#0E0E0E;text-decoration:none;padding:7px 4px 7px 10px}#hf-kit a:hover{color:#B33A16}' +
      '#hf-kit button{border:0;background:none;font:inherit;font-size:15px;line-height:1;padding:6px 9px;cursor:pointer;color:#5E5E59}' +
      '@media (max-width:900px){#hf-kit{display:none}}';
    d.querySelector('button').addEventListener('click', function () { d.remove(); try { sessionStorage.setItem('hf-kit-x', '1'); } catch (e) {} });
    document.head.appendChild(s); document.body.appendChild(d);
  }
  function start() {
    fix(document);
    new MutationObserver(function (ms) {
      ms.forEach(function (m) {
        if (m.type === 'attributes') map(m.target);
        else m.addedNodes.forEach(function (n) { if (n.nodeType === 1) fix(n); });
      });
    }).observe(document.documentElement, { childList: true, subtree: true, attributes: true, attributeFilter: ['href'] });
    // the sims set <html lang> while booting; show the badge in the final language
    setTimeout(badge, 1500);
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start); else start();
})();
`;
}

