function injectShim(htmlFile, spaceDir) {
  let html = fs.readFileSync(htmlFile, 'utf8');
  if (html.includes('hf-space.js')) return;
  const depth = path.relative(path.dirname(htmlFile), spaceDir).split(path.sep).filter(Boolean).length;
  const src = '../'.repeat(depth) + 'hf-space.js';
  if (!/<\/head>/i.test(html)) throw new Error('no </head> in ' + htmlFile);
  html = html.replace(/<\/head>/i, `<script src="${src}"></script><!-- Hugging Face Space shim, see README.md -->\n</head>`);
  fs.writeFileSync(htmlFile, html);
}

function frontMatter(o) {
  if (o.short_description && o.short_description.length > 60) throw new Error('short_description over 60 chars');
  const lines = ['---'];
  for (const [k, v] of Object.entries(o)) {
    if (v == null) continue;
    if (Array.isArray(v)) { lines.push(`${k}:`); for (const x of v) lines.push(`- ${x}`); }
    else lines.push(`${k}: ${typeof v === 'string' && /[:#'"]/.test(v) ? JSON.stringify(v) : v}`);
  }
  lines.push('---', '');
  return lines.join('\n');
}
const licenceMeta = () => CODE_LICENSE
  ? { license: CODE_LICENSE }
  : { license: 'other', license_name: 'mixed-see-license-md', license_link: 'LICENSE.md' };
const codeLine = () => CODE_LICENSE
  ? `printedrobotics.cz's own code in this Space: ${CODE_LICENSE} (see the repository).`
  : `printedrobotics.cz's own code in this Space (simulator UI, missions, setup wizard, arena game code): © printedrobotics.cz. The source is public at https://github.com/artigrib/prlanding, but no open-source licence has been declared for it yet; please ask before reusing it beyond viewing and running this Space.`;
const TAGS = ['robotics', 'lerobot', 'so101', 'mujoco', 'simulation', 'threejs', 'education'];

function check(dir) {
  const files = walk(dir);
  let total = 0; const big = [];
  for (const f of files) {
    const s = fs.statSync(f).size; total += s;
    if (s > LIMITS.file) throw new Error(`${rel(f)} is ${(s / MB).toFixed(1)} MB (limit ${LIMITS.file / MB} MB)`);
    if (s > LIMITS.lfsHint) big.push(`${rel(f)} (${(s / MB).toFixed(1)} MB, stored with Git LFS by upload_folder)`);
  }
  if (total > LIMITS.space) throw new Error(`${rel(dir)} is ${(total / MB).toFixed(1)} MB (limit ${LIMITS.space / MB} MB)`);
  console.log(`${rel(dir)}: ${files.length} files, ${(total / MB).toFixed(1)} MB` + (big.length ? '\n  ' + big.join('\n  ') : ''));
}

