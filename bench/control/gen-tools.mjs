#!/usr/bin/env node
// Auto-translates the MCP bridge's tool surface into OpenAI-style function-calling tools for PR-Bench.
//   node bench/control/gen-tools.mjs          -> writes bench/control/tools.json
//   node bench/control/gen-tools.mjs --check  -> exit 1 if tools.json is stale (CI / unit test)
// Sources (never edited here): backend/bridge-client/schemas.js (JSON Schemas the tab validates against, generated
// from backend/bridge/src/schemas.ts) and the fixed DESCRIPTIONS / ERROR_TEXT / MISSIONS (goal texts) in backend/bridge/src/schemas.ts.
// Relay-only fields (session, request_id, preempt) are dropped: the harness is in-process, one motion at a time.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = path.join(ROOT, 'bench/control/tools.json');

/** Tools the CONTROL track exposes, in a fixed order (stable prompt prefix). start_mission / list_missions are
 *  left out: the harness starts the task's mission itself, so a model cannot switch to an easier one. */
export const BENCH_TOOLS = ['get_state', 'get_scene', 'move_joints', 'move_to', 'run_trajectory', 'set_gripper', 'home', 'stop',
  'check_mission', 'reset_scene', 'snapshot'];
const DROP = new Set(['session', 'request_id', 'preempt']);
/** Harness-only tool: the model says it is finished (same for every model). */
const FINISH = {
  name: 'task_complete',
  description: 'Call this once when you believe the task is done (or you give up). The episode ends and is graded; no further tool calls are accepted.',
  parameters: { type: 'object', properties: { summary: { type: 'string', maxLength: 400, description: 'one or two sentences: what you did' } }, additionalProperties: false }
};

function tsRecord(src, name) {
  const i = src.indexOf(`export const ${name}`);
  if (i < 0) throw new Error('schemas.ts: ' + name + ' not found');
  const body = src.slice(src.indexOf('{', src.indexOf('=', i)) + 1, src.indexOf('\n};', i));
  return body;
}
const unq = (s) => s.replace(/\\'/g, "'");

export function parseDescriptions(src) {
  const out = {};
  for (const m of tsRecord(src, 'DESCRIPTIONS').matchAll(/^\s*([a-z_]+): '((?:[^'\\]|\\.)*)',?\s*$/gm)) out[m[1]] = unq(m[2]);
  return out;
}
export function parseErrorText(src) {
  const out = {};
  for (const m of tsRecord(src, 'ERROR_TEXT').matchAll(/^\s*([A-Z_]+): \{ message: '((?:[^'\\]|\\.)*)', retryable: (true|false)(?:, hint: '((?:[^'\\]|\\.)*)')? \}/gm)) {
    out[m[1]] = { message: unq(m[2]), retryable: m[3] === 'true', ...(m[4] ? { hint: unq(m[4]) } : {}) };
  }
  return out;
}
export function parseMissions(src) {
  const out = {};
  for (const m of tsRecord(src, 'MISSIONS').matchAll(/^\s*([a-z_]+): \{ title_cs: '((?:[^'\\]|\\.)*)', title_en: '((?:[^'\\]|\\.)*)', goal_en: '((?:[^'\\]|\\.)*)' \}/gm)) {
    out[m[1]] = { title_en: unq(m[3]), goal_en: unq(m[4]) };
  }
  return out;
}
function strip(schema) {
  const s = structuredClone(schema);
  if (s.properties) for (const k of Object.keys(s.properties)) if (DROP.has(k)) delete s.properties[k];
  if (Array.isArray(s.required)) { s.required = s.required.filter((k) => !DROP.has(k)); if (!s.required.length) delete s.required; }
  return s;
}

export async function build() {
  const schemas = (await import(pathToFileURL(path.join(ROOT, 'backend/bridge-client/schemas.js')).href)).default;
  const ts = fs.readFileSync(path.join(ROOT, 'backend/bridge/src/schemas.ts'), 'utf8');
  const desc = parseDescriptions(ts), errors = parseErrorText(ts), missions = parseMissions(ts);
  const tools = BENCH_TOOLS.map((name) => {
    if (!schemas.tools[name]) throw new Error('schemas.js has no tool ' + name);
    if (!desc[name]) throw new Error('schemas.ts has no description for ' + name);
    return { type: 'function', function: { name, description: desc[name], parameters: strip(schemas.tools[name]) } };
  });
  tools.push({ type: 'function', function: FINISH });
  if (Object.keys(missions).length !== 10) throw new Error('MISSIONS parse: ' + Object.keys(missions).length);
  if (Object.keys(errors).length < 20) throw new Error('ERROR_TEXT parse: only ' + Object.keys(errors).length);
  return {
    $comment: 'GENERATED by bench/control/gen-tools.mjs from backend/bridge-client/schemas.js + backend/bridge/src/schemas.ts. Do not edit.',
    protocol: schemas.protocol, limits: schemas.limits, tools, errors, missions
  };
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const text = JSON.stringify(await build(), null, 1) + '\n';
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== text) { console.log('bench/control/tools.json is stale: run node bench/control/gen-tools.mjs'); process.exit(1); }
    console.log('tools.json up to date');
  } else { fs.writeFileSync(OUT, text); console.log('wrote bench/control/tools.json'); }
}
